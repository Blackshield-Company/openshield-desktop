#!/usr/bin/env bash
# OpenShield Desktop — Linux desktop integration installer.
#
# Installs the crest into the hicolor theme and writes the .desktop entry so
# KDE/GNOME launchers AND the taskbar/window icon resolve correctly.
#
# CRITICAL (learned 2026-09-18): on KDE/Wayland, KWin reports the window's
# desktopFileName as the BINARY name ("openshield-desktop"), NOT the bundle
# identifier ("com.openshield.desktop"). The taskbar icon only resolves if a
# desktop file with THAT name exists — so we install both names.
#
# Usage: scripts/install-desktop-integration.sh [path-to-binary]
#   default binary: src-tauri/target/release/openshield-desktop
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BIN="${1:-$REPO_ROOT/src-tauri/target/release/openshield-desktop}"
APP_ID="com.openshield.desktop"
KWIN_NAME="openshield-desktop"   # must match the binary name (see header)
ICONS_SRC="$REPO_ROOT/src-tauri/icons"
ICONS_DST="$HOME/.local/share/icons/hicolor"
APPS_DIR="$HOME/.local/share/applications"

if [[ ! -x "$BIN" ]]; then
    echo "error: binary not found or not executable: $BIN" >&2
    echo "build first: (cd src-tauri && cargo build --release)" >&2
    exit 1
fi

# 1. Icons (RGBA PNGs — generated by scripts/generate_icons.py)
for size in 32 64 128 256 512; do
    case $size in
        256) src="128x128@2x.png" ;;
        512) src="icon.png" ;;
        *)   src="${size}x${size}.png" ;;
    esac
    install -Dm644 "$ICONS_SRC/$src" "$ICONS_DST/${size}x${size}/apps/$APP_ID.png"
done

# 2. Desktop entry — absolute icon path beats themed names (launcher caches)
ENTRY="[Desktop Entry]
Type=Application
Name=OpenShield Desktop
Comment=GUI companion for the OpenShield AI coding harness
Exec=$BIN
TryExec=$BIN
Icon=$ICONS_DST/256x256/apps/$APP_ID.png
Categories=Development;
Terminal=false
StartupNotify=true
StartupWMClass=OpenShield Desktop
"
printf '%s\n' "$ENTRY" > "$APPS_DIR/$KWIN_NAME.desktop"
printf '%s\n' "$ENTRY" > "$APPS_DIR/$APP_ID.desktop"

# 3. Refresh caches (best-effort)
update-desktop-database "$APPS_DIR" 2>/dev/null || true
command -v kbuildsycoca6 >/dev/null && kbuildsycoca6 --noincremental >/dev/null 2>&1 || true

echo "OpenShield Desktop integration installed:"
echo "  binary:  $BIN"
echo "  entries: $APPS_DIR/{$KWIN_NAME,$APP_ID}.desktop"
echo "  icons:   $ICONS_DST/*/apps/$APP_ID.png"
echo
echo "NOTE: if the app is already running, restart it — KDE resolves the"
echo "window's desktop file when the window maps, not retroactively."
